/**
 * Resolver-list helpers for the WhiteDNS family — ported verbatim from
 * v1's MasterDnsProfile companion (the numeric-resolver rule is the
 * product's own validity notion; chain validation V7 reuses it).
 */
object WhitednsResolvers {

    fun splitResolvers(raw: String): List<String> =
        raw.split(',', '\n').map { it.trim() }.filter { it.isNotEmpty() && !it.startsWith("#") }

    fun invalidResolvers(raw: String): List<String> =
        splitResolvers(raw).filterNot { isNumericResolver(it) }

    /** IP literal, optionally with `:port`, `[v6]:port`, or `/prefix`. */
    fun isNumericResolver(entry: String): Boolean {
        val text = entry.trim()
        if (text.isEmpty()) return false
        if (looksNumericHost(text)) return true
        val host: String
        if (text.startsWith("[")) {
            val close = text.indexOf(']')
            if (close < 0) return false
            host = text.substring(1, close)
            val rest = text.substring(close + 1)
            if (rest.isNotEmpty() && !isPort(rest.removePrefix(":"))) return false
        } else {
            val sep = text.lastIndexOf(':')
            if (sep < 0) return false
            host = text.substring(0, sep)
            if (!isPort(text.substring(sep + 1))) return false
        }
        return looksNumericHost(host)
    }

    private fun isPort(s: String): Boolean = s.toIntOrNull()?.let { it in 1..65535 } == true

    private fun looksNumericHost(h: String): Boolean {
        val bare = h.substringBefore('/')
        val suffix = h.substringAfter('/', "")
        if (h.contains('/') && suffix.toIntOrNull()?.let { it in 0..128 } != true) return false
        if (bare.isEmpty()) return false
        if (bare.count { it == ':' } >= 2) {
            return bare.all { it.isDigit() || it == ':' || it == '.' || it in "abcdefABCDEF" }
        }
        if (bare.contains(':')) return false
        val parts = bare.split('.')
        return parts.size == 4 && parts.all { p -> p.isNotEmpty() && p.all { it.isDigit() } && p.toIntOrNull()?.let { it in 0..255 } == true }
    }
}

/**
 * Deterministic rendering of a [WhitednsProfile] into the engine's two
 * files (architecture §3.4): `client_config.toml` + `client_resolvers.txt`.
 *
 * Key set: the MasterDns-family keys exactly as v1's MasterDnsProfile
 * emitted them; for the COTTEN engine, the additional keys observed in the
 * Phase 0 spike (phase0-cottendns.md §1: CONFIG_VERSION, TUNNEL_MODE,
 * RESOLVER_TRANSPORT, STARTUP_MODE, LOG_TO_FILE). Two deliberate omissions,
 * both documented in the architecture work:
 *  - no MTU keys: the v2 profile model carries no MTU field, so the
 *    engine's own default stands (the Phase 0 config's MTU values were
 *    that sample's, not a product requirement);
 *  - LISTEN_PORT is the planner-allocated port passed in, never a stored
 *    profile value (§2.4 rule 2).
 */
object WhitednsConfigRenderer {

    data class Rendered(val configToml: String, val resolversTxt: String)

    fun render(profile: WhitednsProfile, listenIp: String = "127.0.0.1", listenPort: Int): Rendered {
        val domains = profile.domains.map { it.trim() }.filter { it.isNotEmpty() }
        val toml = buildString {
            appendLine("# Generated by Damavand v2 -- WhiteDNS-family client config. Do not edit by hand.")
            if (profile.engine == WhitednsEngine.COTTEN) appendLine("CONFIG_VERSION = \"1\"")
            appendLine("DOMAINS = ${domains.joinToString(", ", "[", "]") { tomlString(it) }}")
            appendLine("ENCRYPTION_KEY = ${tomlString(profile.encryptionKey)}")
            appendLine("DATA_ENCRYPTION_METHOD = ${profile.encryptionMethod}")
            appendLine("PROTOCOL_TYPE = \"SOCKS5\"")
            appendLine("LISTEN_IP = ${tomlString(listenIp)}")
            appendLine("LISTEN_PORT = $listenPort")
            appendLine("SOCKS5_AUTH = false")
            appendLine("RESOLVER_BALANCING_STRATEGY = ${profile.balancingStrategy}")
            appendLine("PACKET_DUPLICATION_COUNT = 3")
            appendLine("UPLOAD_COMPRESSION_TYPE = 0")
            appendLine("DOWNLOAD_COMPRESSION_TYPE = 0")
            appendLine("AUTO_DISABLE_TIMEOUT_SERVERS = true")
            if (profile.engine == WhitednsEngine.COTTEN) {
                appendLine("TUNNEL_MODE = ${tomlString(if (profile.tunnelMode == WhitednsMode.COTTENMAX) "cottenmax" else "legacy")}")
                appendLine("RESOLVER_TRANSPORT = ${tomlString(profile.resolverTransport)}")
                appendLine("STARTUP_MODE = \"resolvers\"")
            }
            appendLine("LOG_LEVEL = \"INFO\"")
            if (profile.engine == WhitednsEngine.COTTEN) appendLine("LOG_TO_FILE = false")
        }
        val resolvers = profile.resolvers.map { it.trim() }
            .filter { it.isNotEmpty() && !it.startsWith("#") }
            .joinToString("\n", postfix = "\n")
        return Rendered(toml, resolvers)
    }

    /** v1 MasterDnsProfile.tomlString, verbatim. */
    private fun tomlString(raw: String): String = buildString {
        append('"')
        for (c in raw) when (c) {
            '\\' -> append("\\\\")
            '"' -> append("\\\"")
            '\n' -> append("\\n")
            '\r' -> append("\\r")
            '\t' -> append("\\t")
            else -> if (c.code < 0x20) append("\\u%04X".format(c.code)) else append(c)
        }
        append('"')
    }
}
